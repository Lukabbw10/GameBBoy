    private static final int SPRITE_SIZE = 25;
    private static final double CLOUD_SPEED = 0.3;
    private static final int SUN_PULSE_INTERVAL = 60;

    private final PixelSprite cloud1;
    private final PixelSprite cloud2;
    private final PixelSprite sunSmall;
    private final PixelSprite sunLarge;

    private final int displayWidth;
    private int sunPulseTick = 0;
    private boolean sunLargeVisible = false;

    public Background(PixelDisplay graphic) {
        this.displayWidth = graphic.getPixelWidth();

        cloud1 = toSprite(ARRAY_CLOUD);
        cloud2 = toSprite(ARRAY_CLOUD);
        sunSmall = toSprite(ARRAY_SUN_SMALL);
        sunLarge = toSprite(ARRAY_SUN_LARGE);

        cloud1.setX(30);
        cloud1.setY(30);
        cloud2.setX(130);
        cloud2.setY(50);

        sunSmall.setX(graphic.getPixelWidth() - 45);
        sunSmall.setY(5);
        sunLarge.setX(graphic.getPixelWidth() - 44);
        sunLarge.setY(4);
    }

    private PixelSprite toSprite(int[][] array) {
        var flat = new ArrayList<Integer>();

        for (var col = 0; col < SPRITE_SIZE; col++) {
            for (var row = 0; row < SPRITE_SIZE; row++) {
                flat.add(array[row][col]);
            }
        }

        return new PixelSprite(flat, SPRITE_SIZE, SPRITE_SIZE);
    }

    public void draw(PixelDisplay graphic) {
        moveClouds(graphic);
        pulseSun(graphic);
    }

    private void moveClouds(PixelDisplay graphic) {
        cloud1.setX(cloud1.getX() - CLOUD_SPEED);
        cloud2.setX(cloud2.getX() - CLOUD_SPEED);

        if (cloud1.getX() + SPRITE_SIZE < 0) {
            cloud1.setX(displayWidth);
        }
        if (cloud2.getX() + SPRITE_SIZE < 0) {
            cloud2.setX(displayWidth);
        }

        if (cloud1.getX() >= 0 && cloud1.getX() + SPRITE_SIZE <= displayWidth) {
            cloud1.tick(graphic);
        }
        if (cloud2.getX() >= 0 && cloud2.getX() + SPRITE_SIZE <= displayWidth) {
            cloud2.tick(graphic);
        }
    }

    private void pulseSun(PixelDisplay graphic) {
        sunPulseTick++;
        if (sunPulseTick >= SUN_PULSE_INTERVAL) {
            sunPulseTick = 0;
            sunLargeVisible = !sunLargeVisible;
        }

        if (sunLargeVisible) {
            sunLarge.tick(graphic);
        } else {
            sunSmall.tick(graphic);
        }
    }
